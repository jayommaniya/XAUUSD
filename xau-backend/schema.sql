CREATE TABLE IF NOT EXISTS signals (
  id TEXT PRIMARY KEY,
  symbol TEXT NOT NULL, tf TEXT NOT NULL,
  signal_time_ms BIGINT NOT NULL, received_at_ms BIGINT NOT NULL,
  direction TEXT NOT NULL, mode TEXT NOT NULL,
  score DOUBLE PRECISION NOT NULL, dir5 INTEGER, score5 DOUBLE PRECISION, dir10 INTEGER, score10 DOUBLE PRECISION,
  entry DOUBLE PRECISION NOT NULL, sl DOUBLE PRECISION NOT NULL, tp DOUBLE PRECISION NOT NULL,
  rr DOUBLE PRECISION, atr DOUBLE PRECISION, rsi DOUBLE PRECISION, horizon_min INTEGER,
  reasons TEXT, raw_json TEXT,
  status TEXT NOT NULL, reject_reason TEXT,
  UNIQUE (symbol, tf, signal_time_ms)
);
CREATE TABLE IF NOT EXISTS trades (
  id TEXT PRIMARY KEY,
  signal_id TEXT NOT NULL REFERENCES signals(id),
  direction TEXT NOT NULL,
  entry DOUBLE PRECISION NOT NULL, sl DOUBLE PRECISION NOT NULL, tp DOUBLE PRECISION NOT NULL,
  opened_at_ms BIGINT NOT NULL, expires_at_ms BIGINT NOT NULL,
  closed_at_ms BIGINT, exit_price DOUBLE PRECISION,
  status TEXT NOT NULL,
  pnl_r DOUBLE PRECISION, mfe DOUBLE PRECISION DEFAULT 0, mae DOUBLE PRECISION DEFAULT 0, hold_s INTEGER
);
CREATE TABLE IF NOT EXISTS settings (k TEXT PRIMARY KEY, v TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS ix_trades_status ON trades(status);
CREATE INDEX IF NOT EXISTS ix_signals_time ON signals(signal_time_ms)
